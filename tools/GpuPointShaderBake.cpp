#include <AYShader/ShadercDriver.h>
#include <AYIO/File.h>
#include "../src/detail/GpuPointShaders.h"
#include "../src/detail/GpuPointShaderBinary.h"
#include <array>
#include <filesystem>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <vector>
namespace fs=std::filesystem;
using namespace ayt;
namespace {
struct Stage { const char* name; const char* type; const char* magic; const char* source; };
constexpr std::array<Stage,6> stages={{{"mark","compute","CSH",render::detail::pointgpu::mark},
    {"count","compute","CSH",render::detail::pointgpu::count},
    {"prefix","compute","CSH",render::detail::pointgpu::prefix},
    {"compact","compute","CSH",render::detail::pointgpu::compact},
    {"vertex","vertex","VSH",render::detail::pointgpu::vertex},
    {"fragment","fragment","FSH",render::detail::pointgpu::fragment}}};
void write(const fs::path& path,const void* data,size_t bytes) {
    if(!io::File::atomicWrite(path.string(),data,bytes)) throw std::runtime_error("Cannot publish shader artifact: "+path.string());
}
}
int main(int argc,char** argv) {
    try {
        std::string executable,bgfxInclude,commonInclude; fs::path directory;
        for(int index=1;index<argc;index+=2) {
            if(index+1>=argc) throw std::runtime_error("Missing bake argument value");
            const std::string option=argv[index],value=argv[index+1];
            if(option=="--shaderc") executable=value;
            else if(option=="--bgfx-include") bgfxInclude=value;
            else if(option=="--common-include") commonInclude=value;
            else if(option=="--output") directory=value;
            else throw std::runtime_error("Unknown bake argument: "+option);
        }
        if(executable.empty()||bgfxInclude.empty()||commonInclude.empty()||directory.empty())
            throw std::runtime_error("Usage: AYRenderer_PointShaderBake --shaderc path --bgfx-include path --common-include path --output directory");
        shader::AYShadercDriver compiler(executable);
        std::array<std::vector<uint8_t>,6> binaries;
        for(size_t index=0;index<stages.size();++index) {
            const auto& stage=stages[index]; shader::ShaderCompileRequest request;
            request.scSource=stage.source; request.stage=stage.type; request.platform="windows"; request.profile="s_5_0";
            request.includeDirs={bgfxInclude,commonInclude}; request.varyingdefSource=render::detail::pointgpu::varyings;
            request.timeoutMs=30000; request.outputName=stage.name;
            auto result=compiler.compile(request);
            if(!result.ok) throw std::runtime_error(std::string(stage.name)+": "+result.stderrText);
            if(!render::detail::pointgpu::validBinary(result.bytes,stage.magic,render::detail::pointgpu::binaryHash(result.bytes)))
                throw std::runtime_error(std::string(stage.name)+": invalid compiled bgfx shader container");
            binaries[index]=std::move(result.bytes);
        }
        fs::create_directories(directory);
        std::ostringstream header,manifest;
        header<<"// Generated by AYRenderer_PointShaderBake. Runtime binary data only.\n#pragma once\n#include <cstdint>\n"
            <<"namespace ayt::render::detail::pointgpu::baked {\ninline constexpr uint32_t schema=1;\n"
            <<"inline constexpr const char* backend=\"d3d11\";\ninline constexpr const char* profile=\"s_5_0\";\n";
        manifest<<"{\n  \"schemaVersion\": 1, \"backend\": \"d3d11\", \"profile\": \"s_5_0\",\n  \"stages\": [\n";
        for(size_t index=0;index<stages.size();++index) {
            const auto& stage=stages[index]; const auto& bytes=binaries[index];
            const auto hash=render::detail::pointgpu::binaryHash(bytes);
            header<<"inline constexpr uint8_t "<<stage.name<<"[]={\n";
            for(size_t offset=0;offset<bytes.size();++offset) {
                if(offset%24==0) header<<"    ";
                header<<unsigned(bytes[offset])<<',';
                if(offset%24==23) header<<'\n';
            }
            header<<"\n};\ninline constexpr uint64_t "<<stage.name<<"Hash="<<hash<<"ull;\n";
            write(directory/(std::string(stage.name)+".bin"),bytes.data(),bytes.size());
            manifest<<"    {\"stage\":\""<<stage.name<<"\",\"file\":\""<<stage.name<<".bin\",\"bytes\":"<<bytes.size()
                <<",\"fnv1a64\":\""<<hash<<"\"}"<<(index+1==stages.size()?"\n":",\n");
        }
        header<<"}\n"; manifest<<"  ]\n}\n";
        const auto receipt=manifest.str(),embedded=header.str();
        write(directory/"manifest.json",receipt.data(),receipt.size());
        // Publish the consumed header last, after every stage compiled successfully.
        write(directory/"GpuPointBinaries.h",embedded.data(),embedded.size());
        std::cout<<"Baked six D3D11 point shader stages with AYShader; embedded runtime bundle ready\n";
        return 0;
    } catch(const std::exception& error) { std::cerr<<"Point shader bake failed: "<<error.what()<<'\n'; return 1; }
}
